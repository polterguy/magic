import { RoleRule } from './types';

export function linesToSlots(text: string) {
  return text
    .split('\n')
    .map(line => line.trim())
    .filter(Boolean);
}

/*
 * A role rule is "incomplete" when it has slots but no role: a blank role never matches
 * at runtime, so those slots would be dropped silently. Such a rule blocks generation
 * until it is given a role or removed, so no granted capability is lost quietly.
 * Limit/window/timeout alone do not count — a new rule is seeded with the base values,
 * and those are harmless to drop because they equal the base.
 */
export function ruleIsIncomplete(rule: RoleRule) {
  return !rule.role.trim() && !!rule.slots.trim();
}

/*
 * Appends slot lines to an editor's text, skipping any already present, so a wizard
 * never duplicates a line and never disturbs what is already there.
 */
export function mergeSlots(existing: string, additions: string[]) {
  const have = new Set(
    existing
      .split('\n')
      .map(line => line.trim())
      .filter(Boolean),
  );
  const fresh = additions.filter(line => !have.has(line));
  if (fresh.length === 0) {
    return existing;
  }
  const trimmed = existing.trimEnd();
  return (trimmed ? trimmed + '\n' : '') + fresh.join('\n') + '\n';
}

/*
 * Folder-kind slots take a FOLDER as their argument (Utilities.MatchesFolder) — pinning one
 * to a folder restricts it to that exact folder, not its subfolders. Every other slot below
 * takes a FILENAME (Utilities.MatchesFile) instead, so pinning it to the same bare folder
 * path would be unsatisfiable: no real filename ever equals the empty trailing segment a
 * folder path leaves, and the pin would silently deny every call rather than fail loudly.
 * [io.path.get-folder] is left out of FILE_SLOTS entirely — it is a pure string utility with
 * no filesystem side effect and a third, unrelated matching rule if ever pinned, so it is
 * granted unconditionally alongside Read instead of forced into either shape.
 */
export const FOLDER_KIND_SLOTS = new Set([
  'io.file.list',
  'io.file.list-recursively',
  'io.file.search',
  'io.folder.exists',
  'io.folder.list',
  'io.folder.list-recursively',
  'io.folder.create',
  'io.folder.copy',
  'io.folder.move',
  'io.folder.delete',
]);

export const FILE_SLOTS: Record<string, string[]> = {
  read: [
    'io.file.load',
    'io.file.load.binary',
    'io.file.exists',
    'io.file.list',
    'io.file.list-recursively',
    'io.file.search',
    'io.folder.exists',
    'io.folder.list',
    'io.folder.list-recursively',
  ],
  write: [
    'io.file.save',
    'io.file.save.binary',
    'io.file.copy',
    'io.file.move',
    'io.file.patch',
    'io.file.unzip',
    'io.folder.create',
    'io.folder.copy',
    'io.folder.move',
  ],
  delete: ['io.file.delete', 'io.folder.delete'],
};

/*
 * Builds one slot's vocabulary line for a given folder — folder-kind slots pin the folder
 * verbatim; file-kind slots append a wildcard filename (optionally narrowed to an extension),
 * since that is the only way Utilities.Matches ever admits a real file inside a folder.
 */
export function fileSystemPin(slot: string, folder: string, extension: string): string {
  if (!folder) {
    return slot;
  }
  const normalized = folder.endsWith('/') ? folder : folder + '/';
  if (FOLDER_KIND_SLOTS.has(slot)) {
    return slot + ':' + normalized;
  }
  const ext = extension.trim().replace(/^\.+/, '');
  return slot + ':' + normalized + '*' + (ext ? '.' + ext : '');
}

/*
 * Slots whose pinned argument IS their security boundary — granting one with no pin
 * widens it from "this one file/folder/database/slot" to "anything on the server":
 * [execute]/[signal]/[try-signal]/[execute-file]/[io.file.execute] run arbitrary code or
 * files with full trust; [data.connect] reaches any configured database, including the
 * system one; every file and folder slot reaches any path on the filesystem. A bare
 * line (no ":value") or one ending right after the colon is unpinned.
 */
export const UNPINNED_RISK_SLOTS = new Set([
  'execute',
  'signal',
  'try-signal',
  'execute-file',
  'io.file.execute',
  'data.connect',
  ...FOLDER_KIND_SLOTS,
  ...FILE_SLOTS.read,
  ...FILE_SLOTS.write,
  ...FILE_SLOTS.delete,
]);

/*
 * Scans a rule's slot lines for an unpinned risk slot, returning one warning per line
 * found — surfaced inline so an unpinned grant is never generated by accident.
 */
export function lintSlotLines(lines: string): string[] {
  const warnings: string[] = [];
  for (const raw of linesToSlots(lines)) {
    const colon = raw.indexOf(':');
    const name = colon === -1 ? raw : raw.slice(0, colon);
    const pin = colon === -1 ? '' : raw.slice(colon + 1).trim();
    if (UNPINNED_RISK_SLOTS.has(name) && !pin) {
      warnings.push(
        '"' +
          name +
          '" has no pinned argument — it would reach ANY file, folder, database ' +
          'or slot on the server instead of just one. Pin it, e.g. "' +
          name +
          ':the-one-thing".',
      );
    }
  }
  return warnings;
}
